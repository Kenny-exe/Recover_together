/**
 * Real-database regression test for self-service account deletion.
 *
 * The development database predates Flyway (baselined at V1), so its foreign
 * keys were generated by Hibernate without V1's ON DELETE CASCADE / SET NULL
 * policies. Account deletion used to fail with a 409 Conflict on
 * refresh_tokens; V4 repairs the constraints. Running against the real schema
 * is the only way to prove the cascade actually happens.
 */
@SpringBootTest
@AutoConfigureMockMvc
class AccountDeletionIntegrationTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private RefreshTokenRepository refreshTokenRepository;

    @Autowired
    private UserDeviceRepository userDeviceRepository;

    @Autowired
    private NotificationRepository notificationRepository;

    @Autowired
    private DailyCheckInRepository dailyCheckInRepository;

    @Autowired
    private AchievementRepository achievementRepository;

    @Autowired
    private PartnerRequestRepository partnerRequestRepository;

    @Autowired
    private MessageRepository messageRepository;

    @Autowired
    private RecoveryPlanRepository recoveryPlanRepository;

    @Autowired
    private SupportPlanRepository supportPlanRepository;

    @Autowired
    private SupportRequestRepository supportRequestRepository;

    @Autowired
    private JwtService jwtService;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    private User user;
    private User partner;
    private String token;
    private Long recoveryPlanId;
    private Long supportPlanId;
    private Long retainedSupportRequestId;

    @BeforeEach
    void setUp() {
        String suffix = System.nanoTime() + "";

        user = new User();
        user.setName("Delete Me");
        user.setEmail("delete_" + suffix + "@example.com");
        user.setPassword(passwordEncoder.encode("Password123!"));
        user = userRepository.save(user);

        partner = new User();
        partner.setName("Support Partner");
        partner.setEmail("partner_" + suffix + "@example.com");
        partner.setPassword(passwordEncoder.encode("Password123!"));
        partner = userRepository.save(partner);

        refreshTokenRepository.save(
                new RefreshToken(user, "refresh-" + suffix, LocalDateTime.now().plusDays(30)));

        UserDevice device = new UserDevice();
        device.setUser(user);
        device.setPlatform(DevicePlatform.ANDROID);
        device.setToken("fcm-" + suffix);
        device.setDeviceName("Test phone");
        userDeviceRepository.save(device);

        Notification notification = new Notification();
        notification.setReceiver(user);
        notification.setType(NotificationType.MISSED_CHECKIN);
        notification.setMessage("You missed a check-in");
        notificationRepository.save(notification);

        DailyCheckIn checkIn = new DailyCheckIn();
        checkIn.setUser(user);
        checkIn.setDate(LocalDate.now().minusDays(1));
        checkIn.setStatus(CheckInStatus.SUCCESS);
        dailyCheckInRepository.save(checkIn);

        Message message = new Message();
        message.setSender(user);
        message.setReceiver(partner);
        message.setContent("Hang in there");
        messageRepository.save(message);

        Message received = new Message();
        received.setSender(partner);
        received.setReceiver(user);
        received.setContent("How are you doing?");
        messageRepository.save(received);

        Achievement achievement = new Achievement();
        achievement.setUser(user);
        achievement.setTitle("7 day streak");
        achievementRepository.save(achievement);

        PartnerRequest partnerRequest = new PartnerRequest();
        partnerRequest.setSender(user);
        partnerRequest.setReceiver(partner);
        partnerRequest.setStatus(PartnerRequestStatus.ACCEPTED);
        partnerRequestRepository.save(partnerRequest);

        RecoveryPlan recoveryPlan = new RecoveryPlan(
                user, "Stay sober", List.of("Go for a walk"), List.of("Stress"), List.of("Sponsor"));
        recoveryPlanId = recoveryPlanRepository.save(recoveryPlan).getId();

        SupportPlan supportPlan = new SupportPlan(user, Set.of(SupportAction.SEND_MESSAGE));
        supportPlanId = supportPlanRepository.save(supportPlan).getId();

        // Owned by the deleted user: removed with the account.
        supportRequestRepository.save(new SupportRequest(user, partner, "Need help"));

        // Owned by the partner but pointing at the deleted user: the row is
        // retained and anonymised via ON DELETE SET NULL.
        retainedSupportRequestId = supportRequestRepository
                .save(new SupportRequest(partner, user, "Checking in"))
                .getId();

        token = jwtService.generateToken(user.getEmail());
    }

    @AfterEach
    void tearDown() {
        Long userId = user == null ? null : user.getId();
        Long partnerId = partner == null ? null : partner.getId();
        if (userId == null || partnerId == null) {
            return;
        }

        // Manual cleanup keeps the shared dev database tidy even when the test
        // fails before the cascade under test succeeds.
        jdbcTemplate.update(
                "DELETE FROM recovery_plan_contacts WHERE plan_id IN (SELECT id FROM recovery_plans WHERE user_id IN (?, ?))",
                userId, partnerId);
        jdbcTemplate.update(
                "DELETE FROM recovery_plan_coping_strategies WHERE plan_id IN (SELECT id FROM recovery_plans WHERE user_id IN (?, ?))",
                userId, partnerId);
        jdbcTemplate.update(
                "DELETE FROM recovery_plan_triggers WHERE plan_id IN (SELECT id FROM recovery_plans WHERE user_id IN (?, ?))",
                userId, partnerId);
        jdbcTemplate.update("DELETE FROM recovery_plans WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update(
                "DELETE FROM support_plan_actions WHERE plan_id IN (SELECT id FROM support_plans WHERE user_id IN (?, ?))",
                userId, partnerId);
        jdbcTemplate.update("DELETE FROM support_plans WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM support_requests WHERE user_id IN (?, ?) OR partner_id IN (?, ?)",
                userId, partnerId, userId, partnerId);
        jdbcTemplate.update("DELETE FROM messages WHERE sender_id IN (?, ?) OR receiver_id IN (?, ?)",
                userId, partnerId, userId, partnerId);
        jdbcTemplate.update("DELETE FROM partner_requests WHERE sender_id IN (?, ?) OR receiver_id IN (?, ?)",
                userId, partnerId, userId, partnerId);
        jdbcTemplate.update("DELETE FROM notifications WHERE receiver_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM daily_checkins WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM achievements WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM refresh_tokens WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM user_devices WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM audit_logs WHERE user_id IN (?, ?)", userId, partnerId);
        jdbcTemplate.update("DELETE FROM users WHERE id IN (?, ?)", userId, partnerId);
    }

    @Test
    @DisplayName("DELETE /users/me removes all owned rows, retains audit trail, and nulls partner references")
    void testAccountDeletionCascades() throws Exception {
        Long userId = user.getId();

        mockMvc.perform(delete("/users/me")
                        .header(HttpHeaders.AUTHORIZATION, "Bearer " + token))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.message").value("Account deleted successfully"));

        assertTrue(userRepository.findById(userId).isEmpty(), "user row must be deleted");

        for (String table : List.of("refresh_tokens", "user_devices",
                "daily_checkins", "achievements", "recovery_plans", "support_plans")) {
            assertEquals(0, count("SELECT COUNT(*) FROM " + table + " WHERE user_id = ?", userId),
                    table + " rows must be cascade-deleted");
        }

        assertEquals(0, count("SELECT COUNT(*) FROM notifications WHERE receiver_id = ?", userId),
                "notifications must be cascade-deleted");
        assertEquals(0, count(
                "SELECT COUNT(*) FROM partner_requests WHERE sender_id = ? OR receiver_id = ?",
                userId, userId), "partner requests must be cascade-deleted");
        assertEquals(0, count(
                "SELECT COUNT(*) FROM messages WHERE sender_id = ? OR receiver_id = ?",
                userId, userId), "sent and received messages must be cascade-deleted");
        assertEquals(0, count("SELECT COUNT(*) FROM support_requests WHERE user_id = ?", userId),
                "owned support requests must be cascade-deleted");

        assertEquals(0, count("SELECT COUNT(*) FROM recovery_plan_contacts WHERE plan_id = ?", recoveryPlanId),
                "recovery plan contacts must be cascade-deleted");
        assertEquals(0, count("SELECT COUNT(*) FROM recovery_plan_coping_strategies WHERE plan_id = ?", recoveryPlanId));
        assertEquals(0, count("SELECT COUNT(*) FROM recovery_plan_triggers WHERE plan_id = ?", recoveryPlanId));
        assertEquals(0, count("SELECT COUNT(*) FROM support_plan_actions WHERE plan_id = ?", supportPlanId));

        Long retainedPartnerId = jdbcTemplate.queryForObject(
                "SELECT partner_id FROM support_requests WHERE id = ?", Long.class, retainedSupportRequestId);
        assertNull(retainedPartnerId, "partner_id must be SET NULL, not cascade-deleted");

        assertEquals(1, count(
                "SELECT COUNT(*) FROM audit_logs WHERE user_id = ? AND action = 'ACCOUNT_DELETED'", userId),
                "account deletion must be audited after the user row is gone");
    }

    private int count(String sql, Object... args) {
        Integer value = jdbcTemplate.queryForObject(sql, Integer.class, args);
        return value == null ? 0 : value;
    }
}
